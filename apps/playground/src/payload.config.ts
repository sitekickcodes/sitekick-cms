import { postgresAdapter } from '@payloadcms/db-postgres'
import { mcpPlugin } from '@payloadcms/plugin-mcp'
import { lexicalEditor } from '@payloadcms/richtext-lexical'
import { vercelBlobStorage } from '@payloadcms/storage-vercel-blob'
import { sharpTransformer } from '@payloadcms/transformer-sharp'
import { sitekickCMS } from '@sitekick/cms'
import path from 'path'
import { buildConfig } from 'payload'
import sharp from 'sharp'
import { fileURLToPath } from 'url'

import { Media } from './collections/Media'
import { Pages } from './collections/Pages'
import { People } from './collections/People'
import { Posts } from './collections/Posts'
import { Users } from './collections/Users'
import { SiteSettings } from './globals/SiteSettings'

const filename = fileURLToPath(import.meta.url)
const dirname = path.dirname(filename)

const siteUrl =
  process.env.NEXT_PUBLIC_SERVER_URL ||
  (process.env.VERCEL_PROJECT_PRODUCTION_URL ? `https://${process.env.VERCEL_PROJECT_PRODUCTION_URL}` : '') ||
  'http://localhost:3100'

export default buildConfig({
  admin: {
    user: Users.slug,
    importMap: {
      baseDir: path.resolve(dirname),
      // Generated by hand (`bun run generate:importmap`) so dev hot reload never rewrites it mid-request.
      autoGenerate: false,
    },
  },
  collections: [Pages, Posts, People, Media, Users],
  globals: [SiteSettings],
  editor: lexicalEditor(),
  // Agents use REST and MCP; nothing reads GraphQL.
  graphQL: { disable: true },
  secret: process.env.PAYLOAD_SECRET || '',
  serverURL: siteUrl,
  typescript: {
    outputFile: path.resolve(dirname, 'payload-types.ts'),
  },
  db: postgresAdapter({
    // Migrations only; `push` would let dev drift from what deploys.
    push: false,
    pool: {
      connectionString: process.env.DATABASE_URL || '',
      idleTimeoutMillis: 1000,
      max: 5,
    },
  }),
  ...(process.env.BLOB_READ_WRITE_TOKEN
    ? {
        storage: [
          vercelBlobStorage({
            collections: { media: { prefix: 'media' } },
            token: process.env.BLOB_READ_WRITE_TOKEN,
            addRandomSuffix: false,
            clientUploads: true,
          }),
        ],
      }
    : {}),
  upload: {
    transformers: [sharpTransformer({ sharp })],
  },
  plugins: [
    sitekickCMS({
      site: { name: 'Demo Co.', url: siteUrl, accent: '#0f766e' },
      nav: [
        { label: 'Website', icon: 'globe', links: ['pages', 'site-settings'] },
        { label: 'News', icon: 'newspaper', links: ['posts'] },
        { label: 'People', icon: 'users', links: ['people'] },
        { label: 'Library', icon: 'image', links: ['media'] },
      ],
    }),
    mcpPlugin({}),
  ],
})
